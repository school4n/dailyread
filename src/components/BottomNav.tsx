'use client';

// Bottom Navigation for Mobile
// src/components/BottomNav.tsx

import Link from 'next/link';
import { usePathname } from 'next/navigation';

const NAV_ITEMS = [
  { href: '/', label: 'Home', icon: HomeIcon },
  { href: '/categories', label: 'Chuyên mục', icon: GridIcon },
  { href: '/search', label: 'Tìm kiếm', icon: SearchIcon },
  { href: '/bookmarks', label: 'Đã lưu', icon: BookmarkIcon },
  { href: '/settings', label: 'Cài đặt', icon: SettingsIcon },
];

export function BottomNav() {
  const pathname = usePathname();
  
  // Don't show on admin pages or reader mode (article pages on desktop)
  if (pathname.startsWith('/admin')) return null;
  
  return (
    <nav className="bottom-nav md:hidden" role="navigation" aria-label="Điều hướng chính">
      {NAV_ITEMS.map(({ href, label, icon: Icon }) => {
        const isActive = href === '/' ? pathname === '/' : pathname.startsWith(href);
        return (
          <Link
            key={href}
            href={href}
            className={`bottom-nav__item ${isActive ? 'bottom-nav__item--active' : ''}`}
            aria-label={label}
            aria-current={isActive ? 'page' : undefined}
          >
            <Icon />
            <span>{label}</span>
          </Link>
        );
      })}
    </nav>
  );
}

